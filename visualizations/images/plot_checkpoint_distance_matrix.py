#!/usr/bin/env python3
"""plot_checkpoint_distance_matrix.py.

Generates publication-quality 2D heatmaps visualizing pairwise Euclidean distance
matrices between model checkpoints across optimization trajectories.
Supports single pair visualizations or a multi-run grid sorted by initialization scale.

Required Inputs:
  - cache/runs/{run_id_1}/distances/{run_id_2}_distance.json: Precomputed distance matrix
    JSON generated by `visualizations/preprocessing/compute_checkpoint_distances.py`.
    If missing, preprocessing is automatically executed on demand.

Generated Outputs:
  - plots/checkpoint_distances/distance_{r1}_{r2}.pdf: Single pair vector PDF figure.
  - plots/checkpoint_distances/distance_matrix_grid.pdf: Multi-run grid vector PDF figure.
  - Corresponding 300 DPI raster preview PNG files.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Annotated

import matplotlib.pyplot as plt
import numpy as np
import typer

from privacy_and_grokking.artifacts.cache import DEFAULT_TRACKING_URI
from privacy_and_grokking.artifacts.local import (
    checkpoint_distance_cache_path,
    plots_checkpoint_distance_grid_path,
    plots_checkpoint_distance_path,
)
from privacy_and_grokking.metrics.checkpoint_distance import (
    compute_multiple_runs_distances,
    compute_run_pair_distance,
    fetch_run_init_scale,
)

app = typer.Typer(pretty_exceptions_enable=False)


def format_step(x: float, pos: int | None = None) -> str:
    """Format step numbers cleanly for axis tick labels (e.g. 0, 10k, 50k, 100k, 1M)."""
    if x <= 0:
        return "0"
    if x >= 1_000_000:
        return f"{x / 1_000_000:.1f}M"
    if x >= 1_000:
        return f"{int(x / 1_000)}k" if x % 1_000 == 0 else f"{x / 1_000:.1f}k"
    return f"{int(x)}"


def plot_single_distance_matrix(
    data: dict,
    output_path: Path,
    colormap: str = "viridis",
    dpi: int = 300,
) -> None:
    """Render and save a publication-grade 2D heatmap for a single run pair."""
    matrix = np.array(data["matrix"])  # Shape: (len(steps_1), len(steps_2))
    steps_1 = data["steps_1"]
    steps_2 = data["steps_2"]
    run_name_1 = data.get("run_name_1", data["run_id_1"][:8])
    run_name_2 = data.get("run_name_2", data["run_id_2"][:8])

    fig, ax = plt.subplots(figsize=(7.5, 6.2), dpi=dpi)

    im = ax.imshow(
        matrix,
        origin="lower",
        aspect="auto",
        cmap=colormap,
        interpolation="nearest",
    )

    max_ticks = 8
    n_rows, n_cols = matrix.shape
    x_tick_indices = np.linspace(0, n_cols - 1, min(n_cols, max_ticks), dtype=int)
    y_tick_indices = np.linspace(0, n_rows - 1, min(n_rows, max_ticks), dtype=int)

    ax.set_xticks(x_tick_indices)
    ax.set_xticklabels([format_step(steps_2[i]) for i in x_tick_indices], fontsize=9)

    ax.set_yticks(y_tick_indices)
    ax.set_yticklabels([format_step(steps_1[i]) for i in y_tick_indices], fontsize=9)

    ax.set_xlabel(
        f"Checkpoint Step (Run 2: {run_name_2})", fontsize=10, fontweight="medium", labelpad=8
    )
    ax.set_ylabel(
        f"Checkpoint Step (Run 1: {run_name_1})", fontsize=10, fontweight="medium", labelpad=8
    )

    is_self = data["run_id_1"] == data["run_id_2"]
    if is_self:
        title = (
            f"Checkpoint Distance Matrix: {run_name_1}\n"
            r"($\|\theta(s_i) - \theta(s_j)\|_2$ over optimization trajectory)"
        )
    else:
        title = f"Checkpoint Distance Matrix\nRun 1 ({run_name_1}) vs Run 2 ({run_name_2})"
    ax.set_title(title, fontsize=11, fontweight="bold", pad=12)

    cbar = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label(
        "Euclidean Distance",
        fontsize=9,
        labelpad=10,
    )
    cbar.ax.tick_params(labelsize=8)

    if is_self and n_rows == n_cols:
        ax.plot(
            [0, n_cols - 1],
            [0, n_rows - 1],
            color="white",
            linestyle="--",
            linewidth=1.2,
            alpha=0.7,
        )

    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    pdf_path = output_path.with_suffix(".pdf")
    fig.savefig(pdf_path, format="pdf", bbox_inches="tight")
    print(f"Saved vector PDF figure to: {pdf_path}")

    png_path = output_path.with_suffix(".png")
    fig.savefig(png_path, format="png", dpi=dpi, bbox_inches="tight")
    print(f"Saved high-res PNG figure to: {png_path}")

    plt.close(fig)


def plot_distance_matrix_grid(
    run_ids: list[str],
    pairwise_data: dict[tuple[str, str], dict],
    output_path: Path,
    tracking_uri: str = DEFAULT_TRACKING_URI,
    colormap: str = "viridis",
    dpi: int = 300,
) -> None:
    """Render a K x K grid of heatmaps sorted ascending by initialization scale.

    Columns increase in initialization scale from left to right.
    Rows increase in initialization scale from bottom to top.
    A unified colormap scaling is applied across all subplots for visual comparability.
    """
    # 1. Sort runs ascending by initialization scale
    run_scales = {r: fetch_run_init_scale(r, tracking_uri=tracking_uri) for r in run_ids}
    sorted_runs = sorted(run_ids, key=lambda r: (run_scales[r], r))
    k = len(sorted_runs)

    # 2. Determine global min and max distance across all matrices for consistent color scale

    all_matrices = [
        np.array(pairwise_data[(r1, r2)]["matrix"]) for r1 in sorted_runs for r2 in sorted_runs
    ]
    global_vmin = min(m.min() for m in all_matrices)
    global_vmax = max(m.max() for m in all_matrices)

    # 3. Create subplot grid
    fig, axes = plt.subplots(
        nrows=k,
        ncols=k,
        figsize=(2.8 * k + 1.5, 2.8 * k + 0.8),
        dpi=dpi,
        squeeze=False,
    )

    im = None
    for row_idx, r_row in enumerate(reversed(sorted_runs)):
        # row_idx=0 is top of figure (largest scale), row_idx=k-1 is bottom (smallest scale)
        for col_idx, r_col in enumerate(sorted_runs):
            # col_idx=0 is left of figure (smallest scale), col_idx=k-1 is right (largest scale)
            ax = axes[row_idx, col_idx]
            data = pairwise_data[(r_row, r_col)]
            mat = np.array(data["matrix"])
            steps_1 = data["steps_1"]
            steps_2 = data["steps_2"]

            im = ax.imshow(
                mat,
                origin="lower",
                aspect="auto",
                cmap=colormap,
                vmin=global_vmin,
                vmax=global_vmax,
                interpolation="nearest",
            )

            # Diagonal line for self-distance
            if r_row == r_col and mat.shape[0] == mat.shape[1]:
                ax.plot(
                    [0, mat.shape[1] - 1],
                    [0, mat.shape[0] - 1],
                    color="white",
                    linestyle="--",
                    linewidth=1.0,
                    alpha=0.6,
                )

            # Configure tick marks
            n_rows, n_cols = mat.shape
            x_tick_indices = [0, n_cols // 2, n_cols - 1]
            y_tick_indices = [0, n_rows // 2, n_rows - 1]

            ax.set_xticks(x_tick_indices)
            ax.set_yticks(y_tick_indices)

            # Only show tick labels on the outer boundaries to maintain a clean layout
            is_bottom_row = row_idx == k - 1
            is_left_col = col_idx == 0

            if is_bottom_row:
                ax.set_xticklabels(
                    [format_step(steps_2[i]) for i in x_tick_indices],
                    fontsize=7,
                )
            else:
                ax.set_xticklabels([])

            if is_left_col:
                ax.set_yticklabels(
                    [format_step(steps_1[i]) for i in y_tick_indices],
                    fontsize=7,
                )
            else:
                ax.set_yticklabels([])

            # Bottom column labels
            if is_bottom_row:
                ax.set_xlabel(
                    f"Optimization Steps for\nInitialization Scale {run_scales[r_col]:g}",
                    fontsize=8.5,
                    fontweight="bold",
                    labelpad=6,
                )

            # Left row labels
            if is_left_col:
                ax.set_ylabel(
                    f"Optimization Steps for\nInitialization Scale {run_scales[r_row]:g}",
                    fontsize=8.5,
                    fontweight="bold",
                    labelpad=6,
                )

    # Global colorbar on the right side
    fig.subplots_adjust(right=0.88, top=0.96, bottom=0.08, left=0.08, hspace=0.18, wspace=0.18)
    cbar_ax = fig.add_axes([0.91, 0.15, 0.02, 0.7])
    cbar = fig.colorbar(im, cax=cbar_ax)
    cbar.set_label(
        "Euclidean Distance",
        fontsize=10,
        labelpad=12,
    )
    cbar.ax.tick_params(labelsize=8)


    output_path.parent.mkdir(parents=True, exist_ok=True)

    pdf_path = output_path.with_suffix(".pdf")
    fig.savefig(pdf_path, format="pdf", bbox_inches="tight")
    print(f"Saved vector PDF grid to: {pdf_path}")

    png_path = output_path.with_suffix(".png")
    fig.savefig(png_path, format="png", dpi=dpi, bbox_inches="tight")
    print(f"Saved high-res PNG grid to: {png_path}")

    plt.close(fig)


@app.command()
def main(
    run_ids: Annotated[
        list[str] | None,
        typer.Option(
            "--run-ids",
            "-r",
            help="List of MLflow run IDs to arrange in a sorted heatmap matrix grid.",
        ),
    ] = None,
    run_id_1: Annotated[
        str | None,
        typer.Option("--run-id-1", "-r1", help="First MLflow run ID for single pair plot."),
    ] = None,
    run_id_2: Annotated[
        str | None,
        typer.Option(
            "--run-id-2",
            "-r2",
            help="Second MLflow run ID for single pair plot. Defaults to run-id-1.",
        ),
    ] = None,
    output: Annotated[
        Path | None,
        typer.Option("--output", "-o", help="Target output file path (.pdf or .png)."),
    ] = None,
    tracking_uri: Annotated[
        str,
        typer.Option("--tracking-uri", "-u", help="MLflow server URI."),
    ] = DEFAULT_TRACKING_URI,
    colormap: Annotated[
        str,
        typer.Option(
            "--colormap", "-c", help="Matplotlib colormap name (e.g. viridis, magma, plasma)."
        ),
    ] = "viridis",
    dpi: Annotated[
        int,
        typer.Option("--dpi", help="Raster resolution for PNG output."),
    ] = 300,
) -> None:
    """CLI entrypoint for rendering checkpoint distance heatmaps."""
    # Parse list of run IDs
    target_run_ids: list[str] = []
    if run_ids:
        for item in run_ids:
            target_run_ids.extend([x.strip() for x in item.split(",") if x.strip()])

    if len(target_run_ids) > 1:
        print(f"Rendering distance matrix grid for {len(target_run_ids)} runs...")
        pairwise_data = compute_multiple_runs_distances(
            run_ids=target_run_ids,
            tracking_uri=tracking_uri,
        )
        target_output = output or plots_checkpoint_distance_grid_path("distance_matrix_grid")
        plot_distance_matrix_grid(
            run_ids=target_run_ids,
            pairwise_data=pairwise_data,
            output_path=target_output,
            tracking_uri=tracking_uri,
            colormap=colormap,
            dpi=dpi,
        )
    elif len(target_run_ids) == 1 or run_id_1:
        r1 = target_run_ids[0] if target_run_ids else run_id_1  # type: ignore[index]
        r2 = run_id_2 or r1
        cached_path = checkpoint_distance_cache_path(r1, r2)

        if cached_path.exists():
            data = json.loads(cached_path.read_text())
        else:
            print(f"Cache not found at {cached_path}. Running preprocessing...")
            data = compute_run_pair_distance(
                run_id_1=r1,
                run_id_2=r2,
                tracking_uri=tracking_uri,
            )

        target_output = output or plots_checkpoint_distance_path(r1, r2)
        plot_single_distance_matrix(
            data=data,
            output_path=target_output,
            colormap=colormap,
            dpi=dpi,
        )
    else:
        raise typer.BadParameter("Please provide either --run-ids / -r or --run-id-1 / -r1.")


if __name__ == "__main__":
    app()
